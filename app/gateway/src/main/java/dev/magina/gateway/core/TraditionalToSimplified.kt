    fun foldChar(c: Char): Char {
        if (c < TRAD[0] || c > TRAD[TRAD.lastIndex]) return c
        val index = Arrays.binarySearch(TRAD, c)
        return if (index >= 0) SIMP[index] else c
    }

    /** 1:1 繁→简折叠；无命中字符时走零分配快路径直接返回原字符串引用。 */
    fun fold(text: String): String {
        if (text.isEmpty()) return text
        var out: StringBuilder? = null
        for (i in text.indices) {
            val raw = text[i]
            val mapped = foldChar(raw)
            if (mapped != raw) {
                val sb = out ?: StringBuilder(text.length).also {
                    it.append(text, 0, i)
                    out = it
                }
                sb.append(mapped)
            } else {
                out?.append(raw)
            }
        }
        return out?.toString() ?: text
    }
